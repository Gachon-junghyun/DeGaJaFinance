# ---------------------------------------------------------------- low level
def _shade(cell, hexcolor: str) -> None:
    el = OxmlElement("w:shd")
    el.set(qn("w:val"), "clear")
    el.set(qn("w:fill"), hexcolor)
    cell._tc.get_or_add_tcPr().append(el)


def _borders(cell, **edges) -> None:
    """edges: top/bottom/left/right = (size_eighths, hexcolor) 또는 None(=없음)."""
    tcPr = cell._tc.get_or_add_tcPr()
    for old in tcPr.findall(qn("w:tcBorders")):
        tcPr.remove(old)
    box = OxmlElement("w:tcBorders")
    for edge in ("top", "left", "bottom", "right"):
        spec = edges.get(edge, "keep")
        if spec == "keep":
            continue
        el = OxmlElement(f"w:{edge}")
        if spec is None:
            el.set(qn("w:val"), "nil")
        else:
            size, color = spec
            el.set(qn("w:val"), "single")
            el.set(qn("w:sz"), str(size))
            el.set(qn("w:color"), color)
        box.append(el)
    tcPr.append(box)


def _fixed_layout(t) -> None:
    """Word 자동맞춤을 끄고 지정한 열 너비를 그대로 쓴다."""
    tblPr = t._tbl.tblPr
    for old in tblPr.findall(qn("w:tblLayout")):
        tblPr.remove(old)
    el = OxmlElement("w:tblLayout")
    el.set(qn("w:type"), "fixed")
    tblPr.append(el)


def _repeat_header(row) -> None:
    """페이지가 넘어가도 머리행을 반복한다."""
    trPr = row._tr.get_or_add_trPr()
    el = OxmlElement("w:tblHeader")
    el.set(qn("w:val"), "true")
    trPr.append(el)


def _tight_cjk(doc) -> None:
    """숫자·영문과 한글 사이에 Word 가 자동으로 넣는 간격을 끈다.

    켜져 있으면 '14조'가 '14 조'로, '28.0배'가 '28.0 배'로 벌어진다.
    """
    dd = doc.styles.element.find(qn("w:docDefaults"))
    pPrD = dd.find(qn("w:pPrDefault"))
    pPr = pPrD.find(qn("w:pPr"))
    if pPr is None:
        pPr = OxmlElement("w:pPr")
        pPrD.append(pPr)
    for tag in ("w:autoSpaceDE", "w:autoSpaceDN"):
        el = OxmlElement(tag)
        el.set(qn("w:val"), "0")
        pPr.append(el)
    # 한 줄만 남고 넘어가는 고아행 방지
    wc = OxmlElement("w:widowControl")
    wc.set(qn("w:val"), "1")
    pPr.append(wc)


def _outline(p, level: int) -> None:
    """탐색창/목차가 잡도록 개요 수준을 준다."""
    pPr = p._p.get_or_add_pPr()
    for old in pPr.findall(qn("w:outlineLvl")):
        pPr.remove(old)
    el = OxmlElement("w:outlineLvl")
    el.set(qn("w:val"), str(level))
    pPr.append(el)
    keep = OxmlElement("w:keepNext")
    pPr.append(keep)


def _font(run, size=10.5, bold=False, color=INK, name=BODY_FONT):
    run.font.name = name
    run.font.size = Pt(size)
    run.font.bold = bold
    run.font.color.rgb = color
    run._element.rPr.rFonts.set(qn("w:eastAsia"), name)
    return run


def _space(p, before=0, after=0, line=1.45):
    pf = p.paragraph_format
    pf.space_before = Pt(before)
    pf.space_after = Pt(after)
    pf.line_spacing_rule = WD_LINE_SPACING.MULTIPLE
    pf.line_spacing = line
    return p


def para(doc, text="", size=10.5, bold=False, color=INK, align=None,
         before=0, after=6, line=1.45, indent=0.0):
    p = doc.add_paragraph()
    _space(p, before, after, line)
    if align is not None:
        p.alignment = align
    if indent:
        p.paragraph_format.left_indent = Cm(indent)
    if text:
        _font(p.add_run(text), size, bold, color)
    return p


def rich(doc, chunks, size=10.5, align=WD_ALIGN_PARAGRAPH.JUSTIFY,
         before=0, after=6, line=1.45, indent=0.0):
    """chunks = [(text, bold), ...] — 강조는 최소한으로."""
    p = doc.add_paragraph()
    _space(p, before, after, line)
    p.alignment = align
    if indent:
        p.paragraph_format.left_indent = Cm(indent)
    for text, bold in chunks:
        _font(p.add_run(text), size, bold, NAVY if bold else INK)
    return p


def hrule(doc, before=2, after=8, color=RULE, size=6):
    p = doc.add_paragraph()
    _space(p, before, after, 1.0)
    pPr = p._p.get_or_add_pPr()
    box = OxmlElement("w:pBdr")
    bot = OxmlElement("w:bottom")
    bot.set(qn("w:val"), "single")
    bot.set(qn("w:sz"), str(size))
    bot.set(qn("w:space"), "1")
    bot.set(qn("w:color"), color)
    box.append(bot)
    pPr.append(box)
    return p


def h1(doc, num, text):
    p = doc.add_paragraph()
    _space(p, 20, 2, 1.2)
    _font(p.add_run(f"{num}  "), 14, True, NAVY)
    _font(p.add_run(text), 14, True, NAVY)
    _outline(p, 0)
    hrule(doc, before=0, after=10, color=HEADFILL, size=10)
    return p


def h2(doc, text):
    p = doc.add_paragraph()
    _space(p, 13, 4, 1.2)
    _font(p.add_run(text), 11.5, True, NAVY)
    _outline(p, 1)
    return p


def bullet(doc, text, indent=0.5):
    p = doc.add_paragraph()
    _space(p, 0, 4, 1.4)
    pf = p.paragraph_format
    pf.left_indent = Cm(indent + 0.45)
    pf.first_line_indent = Cm(-0.45)
    _font(p.add_run("· "), 10.5, False, GRAY)
    _font(p.add_run(text), 10.5, False, INK)
    return p


def table(doc, header, rows, widths=None, aligns=None, zebra=True, note=None):
    """가로줄만 있는 편집형 표."""
    ncol = len(header)
    t = doc.add_table(rows=1, cols=ncol)
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    t.autofit = False
    _fixed_layout(t)
    _repeat_header(t.rows[0])
    aligns = aligns or ["l"] * ncol
    amap = {"l": WD_ALIGN_PARAGRAPH.LEFT,
            "c": WD_ALIGN_PARAGRAPH.CENTER,
            "r": WD_ALIGN_PARAGRAPH.RIGHT}

    hdr = t.rows[0]
    for i, txt in enumerate(header):
        c = hdr.cells[i]
        c.vertical_alignment = WD_ALIGN_VERTICAL.CENTER
        p = c.paragraphs[0]
        _space(p, 4, 4, 1.15)
        p.alignment = amap[aligns[i]]
        _font(p.add_run(str(txt)), 9.5, True, RGBColor(0xFF, 0xFF, 0xFF))
        _shade(c, HEADFILL)
        _borders(c, top=None, left=None, right=None, bottom=None)

    for ri, row in enumerate(rows):
        cells = t.add_row().cells
        for i, txt in enumerate(row):
            c = cells[i]
            c.vertical_alignment = WD_ALIGN_VERTICAL.CENTER
            p = c.paragraphs[0]
            _space(p, 3.5, 3.5, 1.2)
            p.alignment = amap[aligns[i]]
            s = str(txt)
            emph = s.startswith("*")
            if emph:
                s = s[1:]
            _font(p.add_run(s), 9.5, emph, NAVY if emph else INK)
            if zebra and ri % 2 == 1:
                _shade(c, ZEBRA)
            _borders(c, top=None, left=None, right=None,
                     bottom=(4, RULE) if ri < len(rows) - 1 else (10, HEADFILL))

    if widths:
        for row in t.rows:
            for i, w in enumerate(widths):
                row.cells[i].width = Cm(w)

    if note:
        p = doc.add_paragraph()
        _space(p, 3, 10, 1.3)
        _font(p.add_run(note), 8.5, False, GRAY)
    else:
        para(doc, "", after=8)
    return t


def callout(doc, title, body):
    t = doc.add_table(rows=1, cols=1)
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    c = t.rows[0].cells[0]
    c.width = Cm(16.4)
    _shade(c, CALLOUT)
    _borders(c, top=None, right=None, bottom=None, left=(24, HEADFILL))
    p = c.paragraphs[0]
    _space(p, 7, 3, 1.3)
    p.paragraph_format.left_indent = Cm(0.35)
    _font(p.add_run(title), 10.5, True, NAVY)
    p2 = c.add_paragraph()
    _space(p2, 0, 7, 1.42)
    p2.paragraph_format.left_indent = Cm(0.35)
    p2.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
    _font(p2.add_run(body), 10, False, INK)
    para(doc, "", after=10)
    return t


def field(p, instr):
    r = p.add_run()
    f1 = OxmlElement("w:fldChar"); f1.set(qn("w:fldCharType"), "begin")
    it = OxmlElement("w:instrText"); it.set(qn("xml:space"), "preserve"); it.text = instr
    f2 = OxmlElement("w:fldChar"); f2.set(qn("w:fldCharType"), "end")
    r._r.append(f1); r._r.append(it); r._r.append(f2)
    return r


