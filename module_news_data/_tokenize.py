# -*- coding: utf-8 -*-
"""토큰화 — 기사 텍스트 → 단어 집합의 **단일 원본** (CLAUDE.md P1).

왜 있나: 신흥어 발굴(`_blindspot.emergent_terms`)이 영어 대문자 정규식으로만 토큰을
뽑아서 **한국어 풀을 통째로 못 봤다**(실측: 한글 제목 71,443건 중 토큰이 나오는 건
17.5%뿐 — 그나마 제목에 박힌 영어를 주운 것). 한글엔 대문자가 없으니 구조적으로 안 보인다.
'안 떠오른 단어는 영영 안 보인다'는 블라인드스팟을 없애려면 축이 한글까지 닿아야 한다.

의존성 0 — 형태소 분석기(konlpy/mecab)는 서드파티라 사람 확인이 필요하고(CLAUDE.md 규약),
없이도 조사 절단만으로 충분히 잡힌다(아래 ⚠ 참조). 표준 라이브러리만 쓴다.

⚠ **조사는 3글자 이상에서만 자른다.** 무조건 자르면 조사와 같은 글자로 끝나는 멀쩡한
2글자 단어가 파괴된다 — 회의→회, 사이→사, 차이→차, 정도→정 (전부 1글자로 뭉개져 탈락).
3글자 규칙이면 엔비디아가→엔비디아, 관세를→관세 는 살리면서 저것들을 지킨다.
(잔여 오차: 지하도→지하 처럼 조사로 끝나는 3글자 명사는 여전히 깎인다. 형태소 분석기
없이 없앨 수 없는 오차라 감수한다 — 발굴 단계의 목적은 recall 이고, 오분해된 토큰은
빈도가 안 튀어서 자연히 하위로 가라앉는다.)

⚠ 판정하지 않는다(P4). 여기서 '일상어/신호어'를 가르지 않는다 — STOP 리스트로 자르는 건
'손으로 적은 고정셋'이라 이 모듈이 없애려는 블라인드스팟 그 자체다. 무엇이 흔한 말인지는
코퍼스가 빈도로 스스로 말하게 두고, 의미 판정은 상위(에이전트)가 한다.
"""
from __future__ import annotations

import html
import re

# 한국어 조사 — 3글자 이상 토큰의 꼬리에서만 절단한다(위 ⚠).
# 긴 것부터 매칭돼야 '으로'가 '로'로 잘리지 않는다 → 정규식 대안 순서 주의.
PARTICLES = (
    "으로", "에서", "에게", "까지", "부터", "보다", "처럼",
    "은", "는", "이", "가", "을", "를", "의", "에", "도", "로", "과", "와", "만",
)
_PARTICLE_RE = re.compile("(" + "|".join(PARTICLES) + ")$")

# 한글 덩어리 / 영문 덩어리를 따로 뽑는다. 'SK하이닉스' → {'SK', '하이닉스'} (의도된 분리).
_RUN_RE = re.compile(r"[가-힣]+|[A-Za-z]+")

MIN_LEN = 2          # 1글자 토큰은 노이즈 — 버린다.
_STRIP_FROM = 3      # 조사 절단 최소 길이(위 ⚠).


def _strip_particle(word: str) -> str:
    """꼬리 조사 절단. 3글자 이상일 때만, 더 못 자를 때까지 **반복**.

    ⚠ 반복이어야 한다 — 조사는 겹쳐 붙는다(실적에도·중국과의·우리와는). 1회만 자르면
    '실적에도'가 '실적에' 로 남아 '실적' 과 다른 단어로 세어진다(실측으로 발견).
    3글자 하한이 매 회차에 걸리므로 2글자 단어(회의·사이)는 어느 단계에서도 안 깎인다.
    """
    while len(word) >= _STRIP_FROM:
        stripped = _PARTICLE_RE.sub("", word, count=1)
        if stripped == word or len(stripped) < MIN_LEN:
            break
        word = stripped
    return word


def tokens(text: str | None) -> set[str]:
    """기사 텍스트 → 단어 집합(문서 내 중복 제거 = DF 계산용).

    · 한글: 조사 절단 후 원형. · 영문: 대문자 정규화(티커·고유명사 대소문자 흡수).
    · HTML 엔티티는 먼저 푼다 — 안 그러면 `&quot;` 가 'QUOT' 라는 유령 단어가 되어
      제목 코퍼스 빈도 2위(3.6%)를 먹는다(스크래퍼 원인은 별도 수정 대상).
    """
    if not text:
        return set()
    out: set[str] = set()
    for run in _RUN_RE.findall(html.unescape(text)):
        if run[0].isascii():
            w = run.upper()
        else:
            w = _strip_particle(run)
        if len(w) >= MIN_LEN:
            out.add(w)
    return out
